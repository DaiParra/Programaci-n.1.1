A = {1,2,3,4}
B = {3,4,5,6}

union = A | B #Para ver la union entre dos conjuntos 
interseccion = A & B #Para ver la interseccion de dos conjuntos 
Diferencia = A - B #Para ver los elementos diferentes que tienen 

print("Union: ", union)
print("Interseccion:", interseccion)
print("Diferencia: ", Diferencia)