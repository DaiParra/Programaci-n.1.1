letras = ["a","b","c","d","e"]

print(letras[0:5]) #Extraer un rango 

print(letras[:2]) #Desde el inicio hasta el nro que vos le digas

print(letras[4:]) #Depende del nro que le des va a eliminar hasta esa cantidad de nro de la lista y muestra los nro que no alcanzo

print(letras[:]) #Copiar lista completa 

print(letras[::3]) #Da saltos 

print(letras[::-1]) #Lista invertida 

print(letras[-3:-1]) #Indices negativos 